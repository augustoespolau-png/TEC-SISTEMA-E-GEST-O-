create or replace function public.tecverde_governanca_touch()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  if tg_table_name = 'perfis_acesso' then
    new.version := coalesce(old.version, 0) + 1;
  end if;
  return new;
end;
$$;

revoke all on function public.tecverde_governanca_touch() from public;

