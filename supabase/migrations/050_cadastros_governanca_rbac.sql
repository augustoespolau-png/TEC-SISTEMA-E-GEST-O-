create or replace function public.governanca_registrar_evento(
  p_acao text,
  p_entidade text,
  p_entidade_id text default null,
  p_antes jsonb default null,
  p_depois jsonb default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.tecverde_is_gestao() then
    raise exception 'Acesso restrito à Gestão' using errcode = '42501';
  end if;

  insert into public.governanca_audit_log (
    actor_id, acao, entidade, entidade_id, antes, depois
  ) values (
    auth.uid(), p_acao, p_entidade, p_entidade_id, p_antes, p_depois
  );
end;
$$;

